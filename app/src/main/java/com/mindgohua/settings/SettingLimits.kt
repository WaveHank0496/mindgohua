package com.mindgohua.settings

/**
 * 每個時間設定的合法範圍。**這是唯一的一份。**
 *
 * ## 為什麼需要這個檔案
 *
 * 這些範圍原本寫在兩個地方：[SettingsStore] 的 `coerceIn`，
 * 以及設定頁對話框的 min/max。**而且兩邊的數字不一樣** ——
 * 門檻在 store 是 `10..7200`，在 UI 是 `30..3600`。
 *
 * 兩邊不一致不會當機、不會有編譯錯誤、不會有任何東西變紅。
 * 它只會產生兩種很難查的症狀：
 *
 * 1. 使用者輸入一個數字，UI 收下了，存進去卻悄悄變成另一個數字。
 * 2. 預設值落在 UI 範圍之外 —— 使用者改掉之後**再也回不去**。
 *
 * 所以合併成一份，並且用測試確認每個預設值都落在自己的範圍內。
 */
object SettingLimits {

    /**
     * 連續使用多久打斷（秒）。
     *
     * 下限 30 秒：再短就變成「一進 app 就跳貓」，那不是提醒，是騷擾。
     * 上限 60 分鐘：超過一小時的話這個 app 等於沒開。
     */
    val THRESHOLD_SECONDS = 30..3600

    /**
     * 切出去多久內回來仍算同一段（秒）。
     *
     * 上限 10 分鐘。放這麼寬是因為「切出去回個訊息再回來」對某些人
     * 真的會超過一分鐘，而那顯然還是同一段。
     */
    val COOLDOWN_SECONDS = 0..600

    /** 解除後多久內不再打斷（分鐘）。 */
    val GRACE_MINUTES = 1..30

    /**
     * 貓出現後幾秒才能按按鈕（秒）。
     *
     * 上限 3 分鐘。研究顯示真正有效的是「可以不進去」這個選項本身，
     * 不是讓人等更久 —— 但想給自己上重鎖的人應該有這個自由。
     * 預設仍然是 3 秒。
     */
    val UNLOCK_DELAY_SECONDS = 0..180
}

/** 夾進某個設定的合法範圍。比 `coerceIn(a.first, a.last)` 好讀。 */
fun Int.clampTo(range: IntRange): Int = coerceIn(range.first, range.last)
